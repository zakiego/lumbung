// Command docgen writes the docs reference pages that come from code:
// Configuration (config.Settings), Error codes (apierr.Codes), the REST API
// (openapi.json, itself generated from the handlers) and the CLI (its
// command tree). CI runs it
// and fails when the committed pages differ, so they can't drift.
//
//	go run ./internal/tools/docgen -out ../site/src/content/docs/docs/reference
package main

import (
	"bytes"
	"flag"
	"fmt"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"strings"

	"github.com/zakiego/lumbung/apps/engine/internal/apierr"
	"github.com/zakiego/lumbung/apps/engine/internal/config"
)

const banner = "{/* Generated by apps/engine/internal/tools/docgen. Don't edit by hand. */}\n\n"

func main() {
	out := flag.String("out", "", "folder for the generated pages")
	spec := flag.String("openapi", "openapi.json", "the OpenAPI document the REST API page is built from")
	flag.Parse()
	if *out == "" {
		log.Fatal("docgen: -out is required")
	}
	if err := os.MkdirAll(*out, 0o755); err != nil {
		log.Fatal(err)
	}
	write(filepath.Join(*out, "configuration.mdx"), configuration())
	write(filepath.Join(*out, "error-codes.mdx"), errorCodes())
	page, err := restAPI(*spec)
	if err != nil {
		log.Fatal(err)
	}
	write(filepath.Join(*out, "rest-api.mdx"), page)
	write(filepath.Join(*out, "cli.mdx"), cliReference())
}

func write(path string, content []byte) {
	if err := os.WriteFile(path, content, 0o644); err != nil {
		log.Fatal(err)
	}
}

func cell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

func configuration() []byte {
	var b bytes.Buffer
	b.WriteString(`---
title: Configuration
description: Every lumbungd setting, its environment variable and its default.
sidebar:
  order: 5
---

`)
	b.WriteString(banner)
	b.WriteString("lumbungd starts with no settings at all. Each setting below is read from its environment variable when that is set and not empty; otherwise the default applies.\n\n")
	b.WriteString("```sh\nLUMBUNG_DATA_DIR=/srv/lumbung LUMBUNG_STATEMENT_TIMEOUT=10s lumbungd\n```\n\n")
	b.WriteString("Durations use Go syntax (`500ms`, `30s`, `5m`). Sizes are bytes, or a number with `KiB`, `MiB`, `GiB`, `TiB` (powers of 1024) or `KB`, `MB`, `GB`, `TB` (powers of 1000).\n\n")
	b.WriteString("| Variable | Kind | Default | What it does |\n|---|---|---|---|\n")
	for _, s := range config.Settings {
		def := "`" + s.Default + "`"
		if s.Default == "" {
			def = "none"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", s.Env, s.Kind, def, cell(s.Doc))
	}
	return b.Bytes()
}

func errorCodes() []byte {
	var b bytes.Buffer
	b.WriteString(`---
title: Error codes
description: Every error code the API returns, with its HTTP status.
sidebar:
  order: 6
---

`)
	b.WriteString(banner)
	b.WriteString("Errors come back as `application/problem+json` with a stable `code`. Match on `code`, not on the message: codes are never renamed or reused.\n\n")
	b.WriteString("```json\n{\n  \"type\": \"about:blank\",\n  \"title\": \"this access can't write\",\n  \"status\": 403,\n  \"code\": \"read_only\",\n  \"detail\": \"sqlite3: attempt to write a readonly database\"\n}\n```\n\n")
	b.WriteString("| Code | HTTP status | Meaning |\n|---|---|---|\n")
	for _, c := range apierr.Codes {
		fmt.Fprintf(&b, "| `%s` | %d %s | %s |\n", c.Code, c.Status, http.StatusText(c.Status), cell(c.Doc))
	}
	return b.Bytes()
}
