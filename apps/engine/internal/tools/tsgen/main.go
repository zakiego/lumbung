// Command tsgen writes the SDK's TypeScript types from openapi.json, so the
// SDK, the API and its docs can't drift (PLAN 7). CI regenerates and diffs.
//
//	go run ./internal/tools/tsgen -openapi openapi.json -out ../../packages/client/src/generated.ts
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"
)

func main() {
	spec := flag.String("openapi", "openapi.json", "the OpenAPI document")
	out := flag.String("out", "", "the TypeScript file to write")
	flag.Parse()
	if *out == "" {
		log.Fatal("tsgen: -out is required")
	}
	raw, err := os.ReadFile(*spec)
	if err != nil {
		log.Fatal(err)
	}
	var doc map[string]any
	if err := json.Unmarshal(raw, &doc); err != nil {
		log.Fatal(err)
	}
	schemas, _ := doc["components"].(map[string]any)["schemas"].(map[string]any)
	names := make([]string, 0, len(schemas))
	for n := range schemas {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Generated by apps/engine/internal/tools/tsgen from apps/engine/openapi.json.\n// Don't edit by hand: run `pnpm --filter @lumbung/engine sdk:gen`.\n\n")
	b.WriteString("/** A value as the API sends it (see the Value encoding docs). */\n")
	b.WriteString("export type WireValue =\n  | { type: \"null\" }\n  | { type: \"integer\"; value: string }\n  | { type: \"float\"; value: number | \"Infinity\" | \"-Infinity\" }\n  | { type: \"text\"; value: string }\n  | { type: \"blob\"; base64: string };\n\n")
	b.WriteString("/** A parameter: a typed value, or plain JSON. */\nexport type WireParam = WireValue | null | boolean | string | number;\n\n")
	for _, n := range names {
		s := schemas[n].(map[string]any)
		if d, _ := s["description"].(string); d != "" {
			b.WriteString(doc1(d, ""))
		}
		fmt.Fprintf(&b, "export interface %s %s\n\n", n, object(s, ""))
	}
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

func doc1(text, indent string) string {
	text = strings.ReplaceAll(text, "*/", "* /")
	return indent + "/** " + text + " */\n"
}

func object(s map[string]any, indent string) string {
	props, _ := s["properties"].(map[string]any)
	required := map[string]bool{}
	if r, ok := s["required"].([]any); ok {
		for _, v := range r {
			required[v.(string)] = true
		}
	}
	keys := make([]string, 0, len(props))
	for k := range props {
		if k != "$schema" {
			keys = append(keys, k)
		}
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("{\n")
	for _, k := range keys {
		p := props[k].(map[string]any)
		if d, _ := p["description"].(string); d != "" {
			b.WriteString(doc1(d, indent+"  "))
		}
		opt := "?"
		if required[k] {
			opt = ""
		}
		fmt.Fprintf(&b, "%s  %s%s: %s;\n", indent, k, opt, tsType(p, indent+"  "))
	}
	if ap, ok := s["additionalProperties"].(map[string]any); ok {
		fmt.Fprintf(&b, "%s  [key: string]: %s;\n", indent, tsType(ap, indent+"  "))
	}
	b.WriteString(indent + "}")
	return b.String()
}

func tsType(s map[string]any, indent string) string {
	if ref, ok := s["$ref"].(string); ok {
		return strings.TrimPrefix(ref, "#/components/schemas/")
	}
	if isValue(s) {
		return "WireValue"
	}
	if isParam(s) {
		return "WireParam"
	}
	if one, ok := s["oneOf"].([]any); ok {
		parts := make([]string, len(one))
		for i, o := range one {
			parts[i] = tsType(o.(map[string]any), indent)
		}
		return strings.Join(parts, " | ")
	}
	if c, ok := s["const"]; ok {
		j, _ := json.Marshal(c)
		return string(j)
	}
	if e, ok := s["enum"].([]any); ok {
		parts := make([]string, len(e))
		for i, v := range e {
			j, _ := json.Marshal(v)
			parts[i] = string(j)
		}
		return strings.Join(parts, " | ")
	}
	switch t := s["type"].(type) {
	case []any:
		parts := make([]string, len(t))
		for i, v := range t {
			c := map[string]any{}
			for k, val := range s {
				c[k] = val
			}
			c["type"] = v
			parts[i] = tsType(c, indent)
		}
		return strings.Join(parts, " | ")
	case string:
		switch t {
		case "string":
			return "string"
		case "integer", "number":
			return "number"
		case "boolean":
			return "boolean"
		case "null":
			return "null"
		case "array":
			items, _ := s["items"].(map[string]any)
			it := tsType(items, indent)
			if strings.Contains(it, "|") {
				it = "(" + it + ")"
			}
			return it + "[]"
		case "object":
			if _, ok := s["properties"]; ok {
				return object(s, indent)
			}
			if ap, ok := s["additionalProperties"].(map[string]any); ok {
				return "Record<string, " + tsType(ap, indent) + ">"
			}
			return "Record<string, unknown>"
		}
	}
	return "unknown"
}

// isValue spots the typed value schema (five titled object variants).
func isValue(s map[string]any) bool {
	one, ok := s["oneOf"].([]any)
	if !ok || len(one) != 5 {
		return false
	}
	first, _ := one[0].(map[string]any)
	return first["title"] == "null"
}

// isParam spots the parameter schema (plain JSON or a typed value).
func isParam(s map[string]any) bool {
	one, ok := s["oneOf"].([]any)
	if !ok || len(one) != 5 {
		return false
	}
	last, _ := one[4].(map[string]any)
	return isValue(last)
}
