// Writes the Dashboard configuration docs page from src/server/settings.ts.
//   node scripts/docgen.ts
import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { SETTINGS } from "../src/server/settings.ts"

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..")
const out = join(root, "apps/site/src/content/docs/docs/reference/dashboard-configuration.md")

const cell = (s: string) => s.replaceAll("|", "\\|")
const rows = SETTINGS.map((s) => `| \`${s.name}\` | ${s.default ? `\`${cell(s.default)}\`` : "none"} | ${cell(s.description)} |`)

const page = `---
title: Dashboard configuration
description: Every environment variable the dashboard reads, with its default.
---

<!-- Generated by apps/dashboard/scripts/docgen.ts from src/server/settings.ts. Don't edit by hand. -->

The dashboard reads these environment variables at start. The engine's settings are in [Configuration](/docs/reference/configuration/).

| Variable | Default | What it does |
|---|---|---|
${rows.join("\n")}
`
writeFileSync(out, page)
console.log(`wrote ${out}`)
